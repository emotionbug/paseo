use serde_json::Value;

pub const OWNER_PERMISSIONS: &[&str] = &[
    "daemon.read",
    "daemon.manage",
    "tunnel.manage",
    "access.manage",
    "workspace.read",
    "workspace.write",
    "workspace.manage",
    "automation.manage",
    "hub.execute",
];

pub fn known_permission(permission: &str) -> bool {
    OWNER_PERMISSIONS.contains(&permission)
}

pub fn allows_inbound(message: &Value, allows: impl Fn(&str) -> bool) -> bool {
    message
        .get("type")
        .and_then(Value::as_str)
        .and_then(inbound)
        .is_some_and(|requirements| {
            requirements.is_empty() || requirements.iter().any(|p| allows(p))
        })
}

pub fn allows_outbound(message: &Value, allows: impl Fn(&str) -> bool) -> bool {
    if message["type"] == "status"
        && matches!(
            message["payload"]["status"].as_str(),
            Some("agent_created" | "agent_create_failed")
        )
    {
        return allows("workspace.write") || allows("hub.execute");
    }
    message
        .get("type")
        .and_then(Value::as_str)
        .and_then(outbound)
        .is_some_and(|requirements| {
            requirements.is_empty() || requirements.iter().any(|p| allows(p))
        })
}

