use super::{GitService, command};
use anyhow::{Result, anyhow};
use serde_json::{Value, json};
use std::path::Path;
use tokio_util::sync::CancellationToken;
impl GitService {
    pub(super) async fn generate_metadata(
        &self,
        cwd: &Path,
        pull_request: bool,
        base: Option<&str>,
        focused_agent_id: Option<&str>,
        cancel: CancellationToken,
    ) -> Result<Value> {
        let compare = if pull_request {
            json!({"mode":"base","baseRef":base,"detail":"full"})
        } else {
            json!({"mode":"uncommitted","detail":"full"})
        };
        let diff = self.read_diff(cwd, &compare, cancel.clone()).await?;
        let mut file_list = String::from("Files changed:\n");
        let mut patch = String::new();
        if !diff["error"].is_null() {
            return Err(anyhow!(
                "{}",
                diff["error"]["message"]
                    .as_str()
                    .unwrap_or("Unable to read Git diff")
            ));
        }
        if let Some(files) = diff["files"].as_array() {
            for file in files {
                let path = file["path"].as_str().unwrap_or("");
                let change = if file["isNew"] == true {
                    "A"
                } else if file["isDeleted"] == true {
                    "D"
                } else if file.get("oldPath").is_some() {
                    "R"
                } else {
                    "M"
                };
                file_list.push_str(&format!(
                    "{change}\t{path}\t(+{} -{})\n",
                    file["additions"], file["deletions"]
                ));
                patch.push_str(&format!("diff --git a/{path} b/{path}\n"));
                if let Some(hunks) = file["hunks"].as_array() {
                    for hunk in hunks {
                        patch.push_str(&format!(
                            "@@ -{},{} +{},{} @@\n",
                            hunk["oldStart"], hunk["oldCount"], hunk["newStart"], hunk["newCount"]
                        ));
                        if let Some(lines) = hunk["lines"].as_array() {
                            for line in lines {
                                patch.push(match line["type"].as_str() {
                                    Some("add") => '+',
                                    Some("remove") => '-',
                                    _ => ' ',
                                });
                                patch.push_str(line["content"].as_str().unwrap_or(""));
                                patch.push('\n');
                            }
                        }
                    }
                }
            }
        }
        let max = if pull_request { 200_000 } else { 120_000 };
        let units: Vec<u16> = patch.encode_utf16().take(max).collect();
        if patch.encode_utf16().count() > max {
            patch = format!(
                "{}\n\n... (diff truncated to {max} chars)\n",
                String::from_utf16_lossy(&units)
            );
        }
        let key = if pull_request {
            "pullRequest"
        } else {
            "commitMessage"
        };
        let mut style = if pull_request {
            "Clear, descriptive title; body explaining what changed and why."
        } else {
            "Concise, imperative mood, no trailing period."
        }
        .to_string();
        let env = self.environment()?;
        if let Ok(root) =
            command::text(cwd, &["rev-parse", "--show-toplevel"], &env, cancel.clone()).await
        {
            if let Ok(bytes) = tokio::fs::read(Path::new(&root).join("paseo.json")).await {
                if let Ok(config) = serde_json::from_slice::<Value>(&bytes) {
                    if let Some(instructions) = config["metadataGeneration"][key]["instructions"]
                        .as_str()
                        .filter(|s| !s.trim().is_empty())
                    {
                        style = instructions.trim().into();
                    }
                }
            }
        }
        let (contract, hint, name, title, schema, fallback) = if pull_request {
            (
                "Write a pull request title and body for the changes below.",
                "Return JSON only with fields 'title' and 'body'.",
                "PullRequest",
                "PR generator",
                json!({"type":"object","properties":{"title":{"type":"string","minLength":1,"maxLength":72},"body":{"type":"string","minLength":1}},"required":["title","body"]}),
                json!({"title":"Update changes","body":"Automated PR generated by Paseo."}),
            )
        } else {
            (
                "Write a concise git commit message for the changes below.",
                "Return JSON only with a single field 'message'.",
                "CommitMessage",
                "Commit generator",
                json!({"type":"object","properties":{"message":{"type":"string","minLength":1,"maxLength":72,"description":"Concise git commit message, imperative mood, no trailing period."}},"required":["message"]}),
                json!({"message":"Update files"}),
            )
        };
        let prompt = format!(
            "{contract}\n\n{style}\n\n{hint}\n\n{file_list}\n\n{}",
            if patch.is_empty() {
                "(No diff available)"
            } else {
                &patch
            }
        );
        let app = self
            .app
            .upgrade()
            .ok_or_else(|| anyhow!("Daemon shutting down"))?;
        let selection = app
            .agents
            .focused_generation_selection(cwd, focused_agent_id)
            .await?;
        match app
            .agents
            .generate_structured_with_selection(
                cwd,
                &prompt,
                &schema,
                name,
                title,
                selection.as_ref(),
                cancel,
            )
            .await
        {
            Ok(value) => Ok(value),
            Err(error)
                if error
                    .downcast_ref::<crate::agent::StructuredAgentFallbackError>()
                    .is_some()
                    || error
                        .downcast_ref::<crate::agent::StructuredAgentResponseError>()
                        .is_some() =>
            {
                tracing::error!(%error,"Structured git metadata generation failed");
                Ok(fallback)
            }
            Err(error) => Err(error),
        }
    }
}
