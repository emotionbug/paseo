Color? syntaxColor(String theme, bool dark, String? token) {
  final role = switch (token) {
    'variable' || 'params' || 'punctuation' => 0,
    'keyword' || 'selector-tag' || 'built_in' => 1,
    'comment' || 'quote' || 'meta' => 2,
    'string' || 'regexp' || 'link' => 3,
    'number' || 'literal' || 'symbol' || 'escape' => 4,
    'title' || 'function' || 'definition' => 5,
    'type' => 6,
    'tag' || 'name' => 7,
    'attr' || 'attribute' || 'property' => 8,
    'operator' => 9,
    'class' => 10,
    'section' || 'heading' => 11,
    _ => null,
  };
  if (role == null) return null;
  return Color((_palettes[theme] ?? _palettes['one']!)[dark ? 0 : 1][role]);
}
